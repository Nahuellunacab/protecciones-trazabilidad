-- ---------- STAGE 2: limpiar catalogos de prueba y cargar datos reales ----------

-- 2.1 Liberar las reles que hoy apuntan a remitos de prueba: se re-vinculan
--     a sus remitos reales (si corresponde) en el paso de UPDATE de rele mas abajo.
UPDATE rele SET remito_id = NULL WHERE remito_id IS NOT NULL;

-- 2.2 Borrar catalogos de prueba/placeholder (sin historial real de movimientos
--     asociado: la tabla movimiento esta vacia antes de esta migracion).
DELETE FROM posicion;
DELETE FROM destino;
DELETE FROM remito;
DELETE FROM proveedor;
DELETE FROM localidad;
DELETE FROM provincia;

-- 2.3 Provincia real
ALTER TABLE tmp_provincia ADD COLUMN real_id BIGINT;
INSERT INTO provincia (nombre)
SELECT nombre FROM tmp_provincia ORDER BY access_id;
UPDATE tmp_provincia t SET real_id = p.id FROM provincia p WHERE p.nombre = t.nombre;

-- 2.4 Localidad real
ALTER TABLE tmp_localidad ADD COLUMN real_id BIGINT;
INSERT INTO localidad (nombre, provincia_id)
SELECT tl.nombre, tp.real_id
FROM tmp_localidad tl
JOIN tmp_provincia tp ON tp.access_id = tl.provincia_access_id
ORDER BY tl.access_id;
UPDATE tmp_localidad t SET real_id = l.id FROM localidad l WHERE l.nombre = t.nombre;

-- 2.5 Destino real (nombre puede repetirse en localidades distintas: se
--     correlaciona por nombre + localidad real, no por nombre solo)
ALTER TABLE tmp_destino ADD COLUMN real_id BIGINT;
WITH ins AS (
    INSERT INTO destino (nombre, direccion, telefono, coordenadas, localidad_id)
    SELECT td.nombre, td.direccion, td.telefono, td.coordenadas, tl.real_id
    FROM tmp_destino td
    JOIN tmp_localidad tl ON tl.access_id = td.localidad_access_id
    RETURNING id, nombre, localidad_id
)
UPDATE tmp_destino t
SET real_id = ins.id
FROM ins
WHERE ins.nombre = t.nombre
  AND ins.localidad_id = (SELECT real_id FROM tmp_localidad WHERE access_id = t.localidad_access_id);

-- 2.6 Posicion real (misma logica: correlacion por nombre + destino real)
ALTER TABLE tmp_posicion ADD COLUMN real_id BIGINT;
WITH ins AS (
    INSERT INTO posicion (nombre, etiqueta, destino_id)
    SELECT tp.nombre, tp.etiqueta, td.real_id
    FROM tmp_posicion tp
    JOIN tmp_destino td ON td.access_id = tp.destino_access_id
    RETURNING id, nombre, destino_id
)
UPDATE tmp_posicion t
SET real_id = ins.id
FROM ins
WHERE ins.nombre = t.nombre
  AND ins.destino_id = (SELECT real_id FROM tmp_destino WHERE access_id = t.destino_access_id);

-- 2.7 Proveedor real
ALTER TABLE tmp_proveedor ADD COLUMN real_id BIGINT;
INSERT INTO proveedor (nombre, domicilio, telefono)
SELECT nombre, domicilio, telefono FROM tmp_proveedor ORDER BY access_id;
UPDATE tmp_proveedor t SET real_id = p.id FROM proveedor p WHERE p.nombre = t.nombre;

-- 2.8 Remito real (asociado se recalcula al final, segun reles que terminen
--     referenciando cada remito)
ALTER TABLE tmp_remito ADD COLUMN real_id BIGINT;
INSERT INTO remito (numero_remito, fecha, proveedor_id, asociado)
SELECT tr.numero_remito, tr.fecha, tp.real_id, false
FROM tmp_remito tr
JOIN tmp_proveedor tp ON tp.access_id = tr.proveedor_access_id
ORDER BY tr.access_id;
UPDATE tmp_remito t SET real_id = r.id FROM remito r WHERE r.numero_remito = t.numero_remito;

-- 2.9 Resolver modelo real (ya estaba completo antes de esta migracion; solo
--     se arma el mapeo access_id -> id real para poder resolver rele.modelo_id)
ALTER TABLE tmp_modelo ADD COLUMN real_id BIGINT;
UPDATE tmp_modelo t
SET real_id = m.id
FROM modelo m
JOIN marca ma ON ma.id = m.marca_id
WHERE m.nombre = t.nombre
  AND ma.nombre = (SELECT real_nombre FROM tmp_marca_map WHERE access_id = t.marca_access_id);

-- 2.10 Agentes -> usuario. Nicolas Cipolletta (legajo Access 10088) ya existe
--      como usuario id=3 (nico.c / OPERADOR): se reutiliza esa cuenta en vez
--      de crear un duplicado. El resto se crean como cuentas historicas sin
--      login (mismo patron que la cuenta "sistema"), usando su legajo de
--      Access como numero_sobre.
ALTER TABLE tmp_agente ADD COLUMN real_id BIGINT;
UPDATE tmp_agente SET real_id = 3 WHERE access_id = 10088;
WITH ins AS (
    INSERT INTO usuario (nombre, apellido, email, password_hash, rol, activo, numero_sobre)
    SELECT ta.nombre, ta.apellido, NULL, NULL, 'AUDITOR', true, ta.access_id::text
    FROM tmp_agente ta
    WHERE ta.access_id <> 10088
    RETURNING id, numero_sobre
)
UPDATE tmp_agente t
SET real_id = ins.id
FROM ins
WHERE ins.numero_sobre = t.access_id::text;

-- 2.11 Completar garantia/remito real de los reles ya existentes en el sistema
--      (fueron importados antes solo con numero_serie + modelo, sin estos datos)
UPDATE rele r
SET garantia_meses = ti.garantia_meses,
    inicio_garantia = ti.inicio_garantia,
    fin_garantia = ti.fin_garantia,
    remito_id = tr.real_id
FROM tmp_ied ti
LEFT JOIN tmp_remito tr ON tr.access_id = ti.remito_access_id
WHERE UPPER(TRIM(r.numero_serie)) = ti.numero_serie;

-- 2.12 Agregar los reles reales que todavia no existian en el sistema
INSERT INTO rele (numero_serie, modelo_id, remito_id, garantia_meses, inicio_garantia, fin_garantia, activo)
SELECT ti.numero_serie, tm.real_id, tr.real_id, ti.garantia_meses, ti.inicio_garantia, ti.fin_garantia, true
FROM tmp_ied ti
JOIN tmp_modelo tm ON tm.access_id = ti.modelo_access_id
LEFT JOIN tmp_remito tr ON tr.access_id = ti.remito_access_id
WHERE NOT EXISTS (
    SELECT 1 FROM rele r WHERE UPPER(TRIM(r.numero_serie)) = ti.numero_serie
);

-- 2.13 Historial real de movimientos (tabla vacia hasta ahora)
INSERT INTO movimiento (fecha_movimiento, notas, rele_id, estado_id, posicion_id, usuario_id)
SELECT tmv.fecha_mov, tmv.notas, r.id, e.id, tp.real_id, ta.real_id
FROM tmp_movimiento tmv
JOIN tmp_ied ti ON ti.access_id = tmv.ied_access_id
JOIN rele r ON UPPER(TRIM(r.numero_serie)) = ti.numero_serie
JOIN tmp_estado_map tem ON tem.access_id = tmv.estado_access_id
JOIN estado e ON e.nombre = tem.real_nombre
JOIN tmp_posicion tp ON tp.access_id = tmv.posicion_access_id
JOIN tmp_agente ta ON ta.access_id = tmv.responsable_access_id
ORDER BY tmv.access_id;

-- 2.14 Recalcular el flag "asociado" de remito segun los reles que quedaron
UPDATE remito SET asociado = true
WHERE id IN (SELECT DISTINCT remito_id FROM rele WHERE remito_id IS NOT NULL);

-- 2.15 Limpieza de tablas temporales de staging
DROP TABLE tmp_provincia, tmp_localidad, tmp_destino, tmp_posicion, tmp_proveedor,
           tmp_remito, tmp_marca_map, tmp_modelo, tmp_agente, tmp_estado_map,
